"""Quality Dashboard — auto-updating markdown dashboard for Quality Sentinel."""
import json, datetime
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
KAOS_ROOT = SCRIPT_DIR.parents[1]
CACHE_DIR = KAOS_ROOT / ".memory" / "cache"
ALERTS_DIR = CACHE_DIR / "alerts"
HEALTH_DIR = CACHE_DIR / "health"
DASHBOARD_FILE = KAOS_ROOT / ".memory" / "dashboard" / "quality-dashboard.md"
STATE_FILE = CACHE_DIR / "quality_orchestrator_state.json"
ALERTS_DIR.mkdir(parents=True, exist_ok=True)


def load_active_alerts():
    alerts = []
    for f in sorted(ALERTS_DIR.glob("*.md"), reverse=True):
        alerts.append({"file": f.name, "content": f.read_text(encoding="utf-8").split('\n')[0][:100]})
    return alerts


def load_latest_health():
    reports = sorted(HEALTH_DIR.glob("health_*.md"), reverse=True)
    if reports:
        return reports[0].read_text(encoding="utf-8")
    return None


def generate_dashboard(pipeline_state=None):
    state = pipeline_state or (json.loads(STATE_FILE.read_text(encoding="utf-8")) if STATE_FILE.exists() else {})
    alerts = load_active_alerts()
    health = load_latest_health()
    now = datetime.datetime.now().isoformat(timespec="minutes") if hasattr(datetime, 'datetime') else str(datetime.datetime.now().isoformat(timespec="minutes"))
    if isinstance(datetime, type):
        now = str(getattr(datetime, 'datetime', datetime).now().isoformat(timespec="minutes"))
    else:
        now = datetime.datetime.now().isoformat(timespec="minutes")
    lines = []
    lines.append("# Quality Sentinel Dashboard")
    lines.append(f"*Updated: {now}*")
    lines.append("")
    lines.append("## Pipeline Status")
    lines.append("")
    lines.append(f"**Last run**: {state.get('last_run', 'Never')}")
    lines.append(f"**Status**: {state.get('pipeline_status', 'never_run')}")
    lines.append("")
    pstatus = state.get('pipeline_status', 'never_run')
    icon = {"passed": "✅", "running": "⏳", "completed_with_failures": "⚠️"}.get(pstatus, "⬜")
    lines.append("| Stage | Status | Details |")
    lines.append("|-------|--------|---------|")
    for stage in ["health_check", "post_output_hook", "session_runner", "verification_chain", "monitor", "dashboard_populate"]:
        s = state.get("stages", {}).get(stage, {})
        status = s.get("status", "never_run")
        icons = {"success": "✅", "failed": "❌", "running": "⏳", "never_run": "⬜"}
        details = s.get("details", "") or s.get("error", "")
        lines.append(f"| {stage} | {icons.get(status, '❓')} {status} | {details} |")
    lines.append("")
    if alerts:
        lines.append("## Active Alerts")
        lines.append("")
        lines.append(f"**{len(alerts)} alert(s)**")
        lines.append("")
        for a in alerts[:5]:
            lines.append(f"- `{a['file']}`: {a['content']}")
        lines.append("")
    if health:
        summary_line = [l for l in health.split('\n') if 'Summary' in l or 'OK' in l or 'Error' in l][:3]
        lines.append("## Health Check")
        lines.append("")
        for l in summary_line:
            lines.append(l)
        lines.append("")
    lines.append("---")
    lines.append(f"*Automatically generated by Quality Sentinel*")
    return "\n".join(lines)


def update_dashboard(pipeline_state=None):
    md = generate_dashboard(pipeline_state)
    DASHBOARD_FILE.parent.mkdir(parents=True, exist_ok=True)
    DASHBOARD_FILE.write_text(md, encoding="utf-8")
    return str(DASHBOARD_FILE)


def view_dashboard():
    if DASHBOARD_FILE.exists():
        print(DASHBOARD_FILE.read_text(encoding="utf-8"))
    else:
        print("No dashboard generated yet. Run 'update' first.")


def main():
    import argparse
    parser = argparse.ArgumentParser(description="Quality Dashboard — auto-updating markdown dashboard for Quality Sentinel")
    subparsers = parser.add_subparsers(dest="command", required=True)
    update_p = subparsers.add_parser("update", help="Generate or update the dashboard")
    view_p = subparsers.add_parser("view", help="View the current dashboard")
    args = parser.parse_args()
    if args.command == "update":
        path = update_dashboard()
        print(f"Dashboard updated: {path}")
    elif args.command == "view":
        view_dashboard()


if __name__ == "__main__":
    main()
