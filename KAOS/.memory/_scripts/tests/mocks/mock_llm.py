"""Mock LLM for deterministic testing — replaces real API calls with canned responses."""


class MockLLMResponse:
    def __init__(self, content: str, model: str = "mock-model"):
        self.content = content
        self.model = model
        self.usage = {"prompt_tokens": 10, "completion_tokens": 10, "total_tokens": 20}


class MockLLM:
    """Deterministic LLM stub for testing."""

    def __init__(self, responses: dict = None, default_response: str = ""):
        self.responses = responses or {}
        self.default_response = default_response or "## Mock Output\n\nGenerated by MockLLM.\n"
        self.call_history = []

    def __call__(self, prompt: str, **kwargs) -> MockLLMResponse:
        self.call_history.append(prompt[:200])
        for key, response in self.responses.items():
            if key.lower() in prompt.lower():
                return MockLLMResponse(response)
        return MockLLMResponse(self.default_response)

    def generate(self, prompt: str, **kwargs) -> str:
        return self.__call__(prompt, **kwargs).content

    def reset(self):
        self.call_history = []

    def last_prompt(self) -> str:
        return self.call_history[-1] if self.call_history else ""


