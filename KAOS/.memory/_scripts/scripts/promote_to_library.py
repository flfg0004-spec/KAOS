#!/usr/bin/env python3
"""Promueve conceptos wiki/ -> library/ cuando audience es public/both y score >= 70.

COPY (no MOVE). SHA256 tracking para divergence detection.

Uso:
  py -3 _scripts/scripts/promote_to_library.py --dry-run
  py -3 _scripts/scripts/promote_to_library.py --apply
  py -3 _scripts/scripts/promote_to_library.py --min-score 50
"""

import argparse
import hashlib
import re
import sys
from datetime import date
from pathlib import Path
from shutil import copy2

from lib.paths import MEMORY_DIR, PROJECT_ROOT

BASE = Path(__file__).resolve().parent.parent.parent  # .memory/
WIKI_CONCEPTS = BASE / "wiki" / "concepts"
WIKI_ENTITIES = BASE / "wiki" / "entities"
LIBRARY_CONCEPTS = BASE / "library" / "concepts"
LIBRARY_ENTITIES = BASE / "library" / "entities"
CACHE_DIR = BASE / "cache" / "promotions"

FRONTMATTER_RE = re.compile(r"^---\s*\n(.*?)\n---", re.DOTALL)

INTERNAL_FIELDS = ["tags_autogenerated", "tags_generated", "embedding"]

SOURCE_MAP = {
    WIKI_CONCEPTS: LIBRARY_CONCEPTS,
    WIKI_ENTITIES: LIBRARY_ENTITIES,
}


def get_audience(frontmatter: str) -> str | None:
    m = re.search(r"^audience:\s*(\S+)", frontmatter, re.MULTILINE)
    return m.group(1) if m else None


def get_score(frontmatter: str) -> int | None:
    m = re.search(r"^score:\s*(\d+)", frontmatter, re.MULTILINE)
    return int(m.group(1)) if m else None


def compute_sha256(content: str) -> str:
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


def transform_frontmatter(fm_text: str, source_rel: str, sha: str) -> str:
    lines = fm_text.split("\n")
    new_lines = []
    for line in lines:
        key = line.split(":")[0].strip() if ":" in line else ""
        if key in INTERNAL_FIELDS or key.startswith("embedding_"):
            continue
        new_lines.append(line)
    new_lines.append(f"promoted_from: {source_rel}")
    new_lines.append(f"promoted_date: {date.today().isoformat()}")
    new_lines.append(f"source_hash: {sha}")
    return "\n".join(new_lines)


def promote_file(src: Path, dst_dir: Path, dry_run: bool) -> dict:
    content = src.read_text(encoding="utf-8")
    match = FRONTMATTER_RE.match(content)
    if not match:
        return {"path": str(src), "status": "no_frontmatter", "action": "skip"}

    fm_text = match.group(1)
    audience = get_audience(fm_text)
    if audience not in ("public", "both"):
        return {"path": str(src), "status": f"audience={audience}", "action": "skip"}

    score = get_score(fm_text)
    min_score = getattr(promote_file, "_min_score", 70)
    if score is not None and score < min_score:
        return {"path": str(src), "status": f"score={score}<{min_score}", "action": "skip"}

    sha = compute_sha256(content)
    dst = dst_dir / src.name
    try:
        source_rel = str(src.relative_to(BASE.parent)).replace("\\", "/")
    except ValueError:
        source_rel = str(src).replace("\\", "/")

    if dst.exists():
        existing_content = dst.read_text(encoding="utf-8")
        existing_sha = compute_sha256(existing_content)
        if existing_sha != sha:
            return {"path": str(src), "status": "diverged", "action": "skip"}
        return {"path": str(src), "status": "exists_identical", "action": "skip"}

    new_fm = transform_frontmatter(fm_text, source_rel, sha)
    new_content = content.replace(fm_text, new_fm, 1)

    if not dry_run:
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(new_content, encoding="utf-8")
        CACHE_DIR.mkdir(parents=True, exist_ok=True)
        (CACHE_DIR / f"{src.stem}.sha256").write_text(sha, encoding="utf-8")

    return {"path": str(src), "status": "promoted", "action": "copy", "sha": sha}


def main():
    parser = argparse.ArgumentParser(description="Promote wiki/ concepts to library/")
    parser.add_argument("--dry-run", action="store_true", default=True, help="Only report (default)")
    parser.add_argument("--apply", action="store_true", help="Actually write changes")
    parser.add_argument("--min-score", type=int, default=70, help="Minimum quality score (default: 70)")
    parser.add_argument("--json", action="store_true", help="Output JSON")
    args = parser.parse_args()

    promote_file._min_score = args.min_score
    dry_run = not args.apply
    json_mode = args.json

    total = {"promoted": 0, "skipped": 0, "diverged": 0, "existing": 0, "no_fm": 0}
    files_results = []

    for src_dir, dst_dir in SOURCE_MAP.items():
        if not src_dir.exists():
            continue
        for f in sorted(src_dir.glob("*.md")):
            result = promote_file(f, dst_dir, dry_run=dry_run)
            status = result["status"]
            file_entry = {"path": str(result["path"]), "status": status}
            if status == "promoted":
                total["promoted"] += 1
                file_entry["reason"] = "copy"
                if not json_mode:
                    prefix = "[DRY-RUN]" if dry_run else "[PROMOTED]"
                    print(f"{prefix} {result['path']} -> {dst_dir.name}/{f.name}")
            elif status == "diverged":
                total["diverged"] += 1
                file_entry["reason"] = "source differs from existing copy"
                if not json_mode:
                    print(f"[DIVERGED] {result['path']} (source differs from existing copy)")
            elif status == "exists_identical":
                total["existing"] += 1
                file_entry["reason"] = "already exists, identical"
            elif status == "no_frontmatter":
                total["no_fm"] += 1
                file_entry["reason"] = "no frontmatter"
            else:
                total["skipped"] += 1
                file_entry["reason"] = status
            files_results.append(file_entry)

    if json_mode:
        output = {
            "promoted": total["promoted"],
            "skipped": total["existing"] + total["no_fm"] + total["skipped"],
            "diverged": total["diverged"],
            "files": files_results,
        }
        print(json.dumps(output, indent=2, ensure_ascii=False))
    else:
        print(f"\nResumen: {total['promoted']} promovidos, {total['existing']} ya existentes, {total['diverged']} divergidos, {total['skipped']} saltados, {total['no_fm']} sin frontmatter")
    return 0


if __name__ == "__main__":
    sys.exit(main())
