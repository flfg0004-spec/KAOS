"""Cleaner: fix dead refs, duplicates, remove pycache, remove deprecated PS."""

import shutil
import re
from pathlib import Path

VAULT = (Path(__file__).resolve().parent.parent.parent)


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return ""


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def fix_dead_refs(dry_run: bool = True) -> str:
    """Create stub files for dead concept references."""
    from lib.scanner import dead_refs
    refs = dead_refs()
    if not refs:
        return "No dead refs to fix."
    created = 0
    for ref in refs:
        target = VAULT / ref["file"]
        if dry_run:
            continue
        if target.suffix == ".md":
            stub = f"---\ntype: concept\nstatus: stub\ndate: {__import__('datetime').datetime.now().strftime('%Y-%m-%d')}\n---\n\n# {target.stem.replace('-', ' ').title()}\n\n*Auto-generated by KGC.*\n"
            _write(target, stub)
            created += 1
    mode = " (dry-run)" if dry_run else ""
    return f"Would create {len(refs)} stubs{mode}" if dry_run else f"Created {created} stub files"


def remove_index_duplicates(dry_run: bool = True) -> str:
    """Remove duplicate entries from index.md."""
    from lib.scanner import duplicates
    dups = duplicates()
    if not dups:
        return "No duplicates to remove."
    index_path = VAULT / "wiki" / "index.md"
    content = _read(index_path)
    for d in dups:
        pattern = f"- [{re.escape(d['b'])}]"
        content = re.sub(rf"^.*{pattern}.*\n?", "", content, flags=re.MULTILINE)
    if not dry_run:
        _write(index_path, content)
    mode = " (dry-run)" if dry_run else ""
    return f"Would remove {len(dups)} duplicates{mode}" if dry_run else f"Removed {len(dups)} duplicates"


def remove_pycache(dry_run: bool = True) -> str:
    """Remove all __pycache__ directories."""
    from lib.scanner import pycache_dirs
    dirs = pycache_dirs()
    if not dirs:
        return "No __pycache__ dirs found."
    if not dry_run:
        for d in dirs:
            shutil.rmtree(d, ignore_errors=True)
    mode = " (dry-run)" if dry_run else ""
    return f"Would remove {len(dirs)} __pycache__ dirs{mode}" if dry_run else f"Removed {len(dirs)} __pycache__ dirs"


def remove_deprecated_ps(dry_run: bool = True) -> str:
    """Remove deprecated .ps1 files."""
    from lib.scanner import deprecated_ps
    files = deprecated_ps()
    if not files:
        return "No deprecated PS files found."
    if not dry_run:
        for f in files:
            f.unlink()
    mode = " (dry-run)" if dry_run else ""
    return f"Would remove {len(files)} deprecated PS files{mode}" if dry_run else f"Removed {len(files)} deprecated PS files"


