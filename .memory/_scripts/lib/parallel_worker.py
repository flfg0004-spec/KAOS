"""Parallel Workers — git worktree-based parallel code generation for Kratos.

Architecture:
  - Planner decomposes task into independent file-level subtasks
  - Each subtask runs in its own git worktree (isolated)
  - Workers execute in parallel, each generating code for their subtask
  - Integrator merges diffs back to main worktree after all complete

Config:
  MAX_WORKERS = 3 (default, configurable)
  WORKTREE_BASE = ".worktrees/" (relative to project root)

Inspired by Cursor Background Agents architecture.
"""

import subprocess
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent.parent
PROJECT_ROOT = SCRIPTS.parent.parent  # KAOS root

MAX_WORKERS = 3
WORKTREE_DIR = PROJECT_ROOT / ".worktrees"


class WorkerTask:
    """A single parallel task for a worker."""
    
    def __init__(self, task_id: str, file_path: str, description: str, prompt: str):
        self.task_id = task_id
        self.file_path = Path(file_path)
        self.description = description
        self.prompt = prompt
        self.result = None
        self.error = None
        self.duration = 0.0


class ParallelWorker:
    """Git worktree-based parallel code generator."""
    
    def __init__(self, max_workers: int = MAX_WORKERS, branch: str = "main"):
        self.max_workers = max_workers
        self.branch = branch
        self.tasks: list[WorkerTask] = []
        self.results: list[dict] = []
    
    def add_task(self, file_path: str, description: str, prompt: str) -> WorkerTask:
        """Add a task for a worker to execute."""
        task = WorkerTask(
            task_id=f"task-{len(self.tasks) + 1}",
            file_path=file_path,
            description=description,
            prompt=prompt,
        )
        self.tasks.append(task)
        return task
    
    def _create_worktree(self, task: WorkerTask) -> Path | None:
        """Create an isolated git worktree for a task."""
        worktree_path = WORKTREE_DIR / task.task_id
        worktree_path.mkdir(parents=True, exist_ok=True)
        
        branch_name = f"kratos-parallel/{task.task_id}"
        
        try:
            result = subprocess.run(
                ["git", "worktree", "add", "-b", branch_name, str(worktree_path), self.branch],
                capture_output=True, text=True, timeout=30,
                cwd=str(PROJECT_ROOT),
            )
            if result.returncode != 0:
                return None
            return worktree_path
        except Exception:
            return None
    
    def _remove_worktree(self, task: WorkerTask):
        """Remove a git worktree after completion."""
        try:
            subprocess.run(
                ["git", "worktree", "remove", str(WORKTREE_DIR / task.task_id)],
                capture_output=True, timeout=30, cwd=str(PROJECT_ROOT),
            )
        except Exception:
            pass
    
    def _run_single_task(self, task: WorkerTask) -> dict:
        """Execute a single task in its worktree.
        
        In real deployment, this calls Kratos agent.
        In test/CLI mode, it writes file content directly.
        """
        import time
        start = time.time()
        
        worktree_path = self._create_worktree(task)
        if not worktree_path:
            task.error = "Failed to create worktree"
            return {"task_id": task.task_id, "status": "error", "error": task.error}
        
        try:
            target_path = worktree_path / task.file_path
            target_path.parent.mkdir(parents=True, exist_ok=True)
            
            # Write the generated code to target file
            target_path.write_text(
                f"# {task.description}\n"
                f"# Generated by Kratos parallel worker\n"
                f"# Task: {task.task_id}\n"
                f"# {datetime.now().isoformat()}\n\n"
                f"# TODO: Code generation would go here\n"
                f"# Prompt: {task.prompt[:100]}...\n"
            )
            
            # Stage the file
            subprocess.run(
                ["git", "add", str(task.file_path)],
                capture_output=True, timeout=30, cwd=str(worktree_path),
            )
            
            task.duration = time.time() - start
            task.result = {
                "file_path": str(task.file_path),
                "worktree": str(worktree_path),
                "size": target_path.stat().st_size,
            }
            
            return {
                "task_id": task.task_id,
                "status": "completed",
                "file_path": str(task.file_path),
                "duration": round(task.duration, 2),
            }
        
        except Exception as e:
            task.error = str(e)
            return {"task_id": task.task_id, "status": "error", "error": str(e)}
        finally:
            self._remove_worktree(task)
    
    def run_all(self) -> list[dict]:
        """Run all tasks in parallel using ThreadPoolExecutor.
        
        Returns:
            List of task result dicts
        """
        if not self.tasks:
            return []
        
        results = []
        with ThreadPoolExecutor(max_workers=self.max_workers) as executor:
            future_to_task = {
                executor.submit(self._run_single_task, task): task
                for task in self.tasks
            }
            
            for future in as_completed(future_to_task):
                task = future_to_task[future]
                try:
                    result = future.result()
                    results.append(result)
                except Exception as e:
                    results.append({
                        "task_id": task.task_id,
                        "status": "error",
                        "error": str(e),
                    })
        
        self.results = results
        return results
    
    def integrate(self) -> dict:
        """Integrate all completed worktree changes back to main branch.
        
        Cherry-picks commits from worktree branches.
        """
        integrated = []
        failed = []
        
        for result in self.results:
            if result["status"] != "completed":
                failed.append(result)
                continue
            
            branch_name = f"kratos-parallel/{result['task_id']}"
            try:
                subprocess.run(
                    ["git", "cherry-pick", branch_name],
                    capture_output=True, timeout=30, cwd=str(PROJECT_ROOT),
                )
                integrated.append(result["task_id"])
            except Exception:
                failed.append(result)
        
        return {
            "integrated": len(integrated),
            "failed": len(failed),
            "tasks": integrated,
            "errors": failed,
        }
    
    def status(self) -> dict:
        """Get worker pool status."""
        return {
            "max_workers": self.max_workers,
            "total_tasks": len(self.tasks),
            "completed": sum(1 for r in self.results if r.get("status") == "completed"),
            "failed": sum(1 for r in self.results if r.get("status") == "error"),
            "branch": self.branch,
        }


if __name__ == "__main__":
    worker = ParallelWorker(max_workers=2)
    
    worker.add_task("src/module_a.py", "Implement module A", "Create a sorting function")
    worker.add_task("src/module_b.py", "Implement module B", "Create a search function")
    worker.add_task("src/module_c.py", "Implement module C", "Create a utility function")
    
    print(f"Running {len(worker.tasks)} tasks with {worker.max_workers} workers...")
    results = worker.run_all()
    
    for r in results:
        print(f"  [{r['status']}] {r.get('task_id', '?')} - {r.get('file_path', '?')} ({r.get('duration', 0)}s)")
    
    print(f"\nStatus: {worker.status()}")
