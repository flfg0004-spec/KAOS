"""Mermaid visualization generator for KAOS vault.

Generates .md files with embedded Mermaid diagrams that render
automatically in GitHub, VS Code, GitLab, and Obsidian.
"""

import re
from pathlib import Path
from datetime import datetime

BASE = Path(__file__).resolve().parent.parent.parent
WIKI = BASE / "wiki"
RAW = BASE / "raw"
SCHEMA = BASE / "schema"
CACHE = BASE / "cache"
QUALITY_DIR = BASE.parent / ".vault" / "quality"


def _wikilinks_to_mermaid(graph_name: str = "knowledge-graph") -> str:
    pages = {}
    for f in sorted(WIKI.rglob("*.md")):
        if ".git" in f.parts or "_pending" in f.parts:
            continue
        rel = f.relative_to(BASE).as_posix()
        content = f.read_text(encoding="utf-8", errors="replace")
        links = set()
        for m in re.finditer(r"\[\[([^\]]+?)\]\]", content):
            target = m.group(1).split("|")[0].split("#")[0].strip()
            if target and target.lower() not in {"wikilink", "wikilinks", "todo", "wip", "update"} and len(target) > 1:
                links.add(target)
        label = f.stem.replace("-", " ").title()
        pages[f.stem] = {"label": label, "links": links, "rel": rel}

    if not pages:
        return "graph TD\n  N[No pages found]"

    lines = [f"graph TD"]
    for name, data in pages.items():
        safe_id = re.sub(r"[^a-zA-Z0-9]", "_", name)[:30]
        display = data["label"][:40]
        lines.append(f'  {safe_id}["{display}"]')
        for link in data["links"]:
            if link in pages:
                target_id = re.sub(r"[^a-zA-Z0-9]", "_", link)[:30]
                lines.append(f"  {safe_id} --> {target_id}")

    if len(lines) > 100:
        lines = lines[:100]
        lines.append("  %% graph truncated to 100 lines")

    return "\n".join(lines)


def _pipeline_flowchart() -> str:
    return """flowchart LR
  subgraph Pipeline["KAOS Knowledge Pipeline"]
    direction LR
    A[Aletheia<br/>Research] --> K[Kosmos<br/>Architecture]
    K --> M[Metis<br/>Strategy]
    M --> R[Kratos<br/>Code]
    R --> N[Mnemosyne<br/>Curation]
  end
  style A fill:#4A90D9,color:#fff
  style K fill:#7B68EE,color:#fff
  style M fill:#E8A87C,color:#fff
  style R fill:#DC143C,color:#fff
  style N fill:#C0C0C0,color:#000"""


def _quality_timeline() -> str:
    sessions = sorted(QUALITY_DIR.glob("**/*score*.json"))
    if not sessions:
        sessions = sorted(QUALITY_DIR.glob("**/*.json"))

    points = []
    for f in sessions[:20]:
        try:
            data = __import__("json").loads(f.read_text(encoding="utf-8"))
            score = data.get("composite") or data.get("score") or 0
            stamp = f.stem.split("session-")[-1][:8] if "session-" in f.stem else f.stem[:10]
            if isinstance(score, (int, float)) and score > 0:
                points.append((stamp, score))
        except Exception:
            continue

    if not points:
        return "timeline\n  title Quality Scores\n  No data yet"

    lines = ["timeline"]
    lines.append("  title Quality Scores Over Time")
    for stamp, score in points[-10:]:
        lines.append(f"  {stamp} : Score {score:.0f}/100")

    return "\n".join(lines)


def _log_timeline() -> str:
    log_path = WIKI / "log.md"
    if not log_path.exists():
        return "timeline\n  title Vault Timeline\n  No log entries yet"

    content = log_path.read_text(encoding="utf-8", errors="replace")
    entries = re.findall(r"^## \[(\d{4}-\d{2}-\d{2})\].*$", content, re.MULTILINE)
    if not entries:
        return "timeline\n  title Vault Timeline\n  No dated entries"

    lines = ["timeline"]
    lines.append("  title Vault Activity Timeline")
    dates = sorted(set(entries))[-15:]
    for d in dates:
        count = entries.count(d)
        items = "entry" if count == 1 else "entries"
        lines.append(f"  {d} : {count} {items}")

    return "\n".join(lines)


def generate_all(output_dir: Path | None = None) -> list[Path]:
    """Generate all visualization files. Returns list of created file paths."""
    if output_dir is None:
        output_dir = BASE

    outputs = []

    graph_md = _wikilinks_to_mermaid()
    p = output_dir / "VIZ_GRAPH.md"
    p.write_text(
        f"<!-- Auto-generated by vault.py viz on {datetime.now().strftime('%Y-%m-%d %H:%M')} -->\n\n"
        "# Knowledge Graph\n\n"
        "```mermaid\n"
        f"{graph_md}\n"
        "```\n",
        encoding="utf-8",
    )
    outputs.append(p)

    pipeline_md = _pipeline_flowchart()
    p = output_dir / "VIZ_PIPELINE.md"
    p.write_text(
        f"<!-- Auto-generated by vault.py viz on {datetime.now().strftime('%Y-%m-%d %H:%M')} -->\n\n"
        "# Pipeline Flow\n\n"
        "```mermaid\n"
        f"{pipeline_md}\n"
        "```\n",
        encoding="utf-8",
    )
    outputs.append(p)

    quality_md = _quality_timeline()
    p = output_dir / "VIZ_QUALITY.md"
    p.write_text(
        f"<!-- Auto-generated by vault.py viz on {datetime.now().strftime('%Y-%m-%d %H:%M')} -->\n\n"
        "# Quality Trend\n\n"
        "```mermaid\n"
        f"{quality_md}\n"
        "```\n",
        encoding="utf-8",
    )
    outputs.append(p)

    timeline_md = _log_timeline()
    p = output_dir / "VIZ_TIMELINE.md"
    p.write_text(
        f"<!-- Auto-generated by vault.py viz on {datetime.now().strftime('%Y-%m-%d %H:%M')} -->\n\n"
        "# Vault Timeline\n\n"
        "```mermaid\n"
        f"{timeline_md}\n"
        "```\n",
        encoding="utf-8",
    )
    outputs.append(p)

    return outputs
